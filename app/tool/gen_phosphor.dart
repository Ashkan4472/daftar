// Generates lib/icons/phosphor_codepoints.g.dart from the installed
// phosphor_flutter package. Run: dart run tool/gen_phosphor.dart
import 'dart:io';
import 'dart:isolate';

Future<void> main() async {
  final uri = await Isolate.resolvePackageUri(
      Uri.parse('package:phosphor_flutter/src/phosphor_icons_regular.dart'));
  final src = File.fromUri(uri!).readAsStringSync();
  final re = RegExp(r"regular/([a-z0-9-]+)\.svg\)\s*\n\s*static const \w+ = PhosphorFlatIconData\((0x[0-9a-f]+)");
  final out = StringBuffer('// GENERATED by tool/gen_phosphor.dart. Do not edit.\n'
      'const phosphorCodepoints = <String, int>{\n');
  var n = 0;
  for (final m in re.allMatches(src)) {
    out.writeln("  '${m[1]}': ${m[2]},");
    n++;
  }
  out.writeln('};');
  File('lib/icons/phosphor_codepoints.g.dart').writeAsStringSync(out.toString());
  stdout.writeln('$n icons');
}
